import { useCallback, useState } from 'react'
import { data } from '../data'
import type { DocumentRow } from '../data/types'
import { useAsync } from '../hooks/useAsync'
import { lkr, shortDate } from '../lib/format'
import { Card, Chip, InlineError, Mono, PageHeader, Skeleton, Toast } from '../ui/primitives'

function Paper({ doc }: { doc: DocumentRow }) {
  return (
    <div className="paper" aria-label={`${doc.kind} preview for ${doc.orderNumber}`}>
      <div className="paper__row" style={{ alignItems: 'baseline' }}><span className="paper__brand">SellBot.lk</span><span style={{ fontSize: 'var(--fs-12)' }}>{doc.kind.toUpperCase()}</span></div>
      <p style={{ marginTop: 22 }}>{doc.orderNumber} · {shortDate(doc.date)}</p>
      <p style={{ marginTop: 6 }}>{doc.customer}</p>
      <hr />
      {doc.items.map((i) => <p className="paper__row" key={i.name}><span>{i.name} × {i.qty}</span><span>{lkr(i.total)}</span></p>)}
      <hr />
      <p className="paper__row" style={{ fontWeight: 700 }}><span>Total</span><span>{lkr(doc.total)}</span></p>
    </div>
  )
}

export default function Documents() {
  const [state, reload] = useAsync(() => data.documents(), [])
  const [sel, setSel] = useState(1)
  const [toast, setToast] = useState('')
  const clear = useCallback(() => setToast(''), [])
  return (
    <>
      <PageHeader eyebrow="Records" title={<>Documents{data.mode === 'live' && <span className="sim-tag"><Chip tone="violet">Simulated · no invoice list API</Chip></span>}</>} />
      {state.status === 'loading' && <Card><Skeleton /></Card>}
      {state.status === 'error' && <InlineError title="Could not load documents" body="Check your connection and try again." onRetry={reload} />}
      {state.status === 'ready' && (() => {
        const docs = state.data.data
        const current = docs.find((d) => d.id === sel) ?? docs[0]
        return (
          <div className="doc-grid">
            <Card className="card-pad-table">
              <div className="tbl-scroll">
                <table className="tbl">
                  <thead><tr><th>Document</th><th>Order</th><th>Customer</th><th>Date</th><th><span className="sr-only">File</span></th></tr></thead>
                  <tbody>
                    {docs.map((d) => (
                      <tr key={d.id} className="is-link" aria-selected={d.id === current?.id} onClick={() => setSel(d.id)} style={{ height: 52 }}>
                        <td style={{ height: 52 }}><Chip tone="green">{d.kind}</Chip></td>
                        <td><Mono>{d.orderNumber}</Mono></td>
                        <td style={{ color: 'var(--c-text)' }}>{d.customer}</td>
                        <td style={{ color: 'var(--c-text)' }}>{shortDate(d.date)}</td>
                        <td><button type="button" className="cell-link" style={{ color: 'var(--c-mint)' }} onClick={(e) => { e.stopPropagation(); setSel(d.id) }} aria-label={`Preview ${d.kind.toLowerCase()} PDF for ${d.orderNumber}`}>PDF</button></td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            </Card>
            {current && (
              <Card className="card-pad" aria-label="Document preview">
                <Paper doc={current} />
                {/* Drawn as a blank white pill in the design (no visible label). Accessible name added. */}
                <button type="button" className="btn btn--white btn--md paper-btn" aria-label={`Download ${current.kind.toLowerCase()} PDF`}
                  onClick={() => setToast('Simulated: PDF files are generated by the backend and sent on WhatsApp.')} />
              </Card>
            )}
          </div>
        )
      })()}
      {toast && <div className="toast-host"><Toast message={toast} onDone={clear} /></div>}
    </>
  )
}
